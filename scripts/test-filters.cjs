const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('app.js','utf8');
const extract=(start,end)=>source.slice(source.indexOf(start),source.indexOf(end,source.indexOf(start)));
const ctx={state:{f:{category:new Set(),width:new Set(),source:new Set(),writing:new Set(),tech:new Set()},fmode:{},q:'',enabledOnly:false},available:f=>!f.unavailable,desktop:{isEnabled:f=>!!f.enabled}};
vm.createContext(ctx);
vm.runInContext(extract('function fontWidths(', 'const WRITING_LABELS')+extract('function matches(', 'const autoBlurb')+extract('function passes(', 'function syncPanel'),ctx);
const font=(values={})=>({n:'Example',c:'sans',source:'google',a:[],s:[],t:[],u:[],subsets:['latin'],w:[400],hay:'example',...values});
const widths=f=>Array.from(ctx.fontWidths(f));
assert.deepEqual(widths(font()),['unspecified']);
assert.deepEqual(widths(font({n:'Example Condensed'})),['condensed']);
assert.deepEqual(widths(font({labels:{a:['wide']},a:undefined})),['wide']);
assert.deepEqual(widths(font({axes:[{tag:'wdth',min:75,max:125}]})),['condensed','standard','wide','adjustable']);
assert.deepEqual(widths(font({axes:{wdth:{min:'100',max:'150'}}})),['standard','wide','adjustable']);
assert.deepEqual(widths(font({axes:[{tag:'wdth',min:100,max:100}]})),['standard']);
assert.deepEqual(widths(font({axes:[{tag:'wdth',min:80,max:90}]})),['condensed','adjustable']);
assert.deepEqual(widths(font({axes:[{tag:'wdth',min:200,max:50}]})),['unspecified']);
assert.deepEqual(widths(font({axes:[{tag:'wght',min:100,max:900}]})),['unspecified']);
assert.equal(ctx.matches(font({noItal:false}),'tech','italic'),true);
assert.equal(ctx.matches(font(),'tech','italic'),false);
assert.equal(ctx.matches(font({c:'slab'}),'category','serif'),true);
assert.equal(ctx.matches(font({c:'serif',s:['serif:slab']}),'category','slab'),true);
const filterContext={q:'',col:null};
ctx.state.f.width=new Set(['condensed','wide']);
assert.equal(ctx.passes(font({n:'Example Condensed'}),filterContext),true,'Widths are alternatives');
assert.equal(ctx.passes(font(),filterContext),false,'Unknown widths are not standard');
ctx.state.f.source.add('fontsource');
assert.equal(ctx.passes(font({n:'Example Condensed'}),filterContext),false,'Sections narrow one another');
assert.equal(ctx.passes(font({n:'Example Condensed',source:'fontsource'}),filterContext),true);
assert.equal(ctx.passes(font({n:'Example Standard',source:'fontsource'}),filterContext,{set:'width',skip:true}),true,'Facet candidates preserve other sections');
ctx.state.f.source.clear();ctx.state.f.width.clear();ctx.state.f.writing.add('arabic');
assert.equal(ctx.passes(font(),filterContext),false);
assert.equal(ctx.passes(font({subsets:['arabic','latin']}),filterContext),true);
ctx.state.f.writing.clear();ctx.state.f.tech=new Set(['variable','italic']);ctx.state.fmode.tech='all';
assert.equal(ctx.passes(font({v:true,noItal:true}),filterContext),false);
assert.equal(ctx.passes(font({v:true,noItal:false}),filterContext),true);
ctx.state.f.tech.clear();ctx.state.f.width.add('wide');
assert.equal(ctx.passes(font({n:'Example Condensed'}),filterContext,{set:'width',k:'condensed',only:true}),true,'Facet count replaces its own section');
assert.equal(ctx.passes(font({n:'Example Expanded',unavailable:true}),filterContext),false);
ctx.state.enabledOnly=true;
assert.equal(ctx.passes(font({n:'Example Expanded'}),filterContext),false);
assert.equal(ctx.passes(font({n:'Example Expanded',enabled:true}),filterContext),true);
const catalog=JSON.parse(fs.readFileSync('data/catalog.json','utf8')).fonts;
assert(widths(catalog.find(f=>f.n==='Roboto Flex')).includes('adjustable'));
assert(widths(catalog.find(f=>f.n==='Roboto Condensed')).includes('condensed'));
assert(widths(catalog.find(f=>f.n==='Inter')).includes('unspecified'));
console.log('Filters: catalog widths, missing metadata, writing systems, any/all combinations, facet counts, availability and enabled-only passed.');
